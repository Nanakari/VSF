import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

export const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Shared by build and validation so checked-in deployment output cannot drift
// from the modular source. No filesystem writes happen here.
export async function bundleWorker() {
  const read = (relative) => fs.readFileSync(path.join(projectDir, relative), "utf8");
  let entry = read("worker/index.js");
  for (const [token, file] of Object.entries({
    __SITE_HTML__: "site/index.html",
    __SITE_CSS__: "site/styles.css",
    __SITE_JS__: "site/app.js",
    __SITE_FAVICON__: "site/favicon.svg",
  })) {
    const placeholder = `"${token}"`;
    if (!entry.includes(placeholder)) throw new Error(`Missing Worker placeholder: ${token}`);
    entry = entry.replace(placeholder, () => JSON.stringify(read(file)));
  }
  const result = await build({
    absWorkingDir: projectDir,
    stdin: { contents: entry, resolveDir: path.join(projectDir, "worker"), sourcefile: "worker/index.js" },
    bundle: true,
    write: false,
    format: "esm",
    platform: "browser",
    target: "es2022",
    charset: "utf8",
    legalComments: "none",
    banner: { js: "// Generated by npm run build. Edit worker/ or site/, then rebuild." },
    metafile: true,
  });
  if (Object.values(result.metafile.outputs).some((output) => output.imports.length > 0)) {
    throw new Error("The deployable Worker must not contain external imports");
  }
  return result.outputFiles[0].text;
}
